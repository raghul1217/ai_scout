function getFaviconUrl(url: string): string {
  try {
    const domain = new URL(url).hostname.replace(/^www\./, "");
    return `https://www.google.com/s2/favicons?domain=${domain}&sz=128`;
  } catch {
    return "https://www.google.com/s2/favicons?domain=savzyen.si&sz=128";
  }
}

export async function seedFreeTools() {
  console.log("Starting Seeding of Free & Freemium AI Tools into Supabase...");

  // 1. Ensure categories exist
  const categoryMap = new Map<string, string>();
  for (const cat of CATEGORIES_DATA) {
    const record = await prisma.category.upsert({
      where: { slug: cat.slug },
      update: {
        name: cat.name,
        color: cat.color,
        description: cat.description,
        sortOrder: cat.sortOrder,
      },
      create: {
        slug: cat.slug,
        name: cat.name,
        color: cat.color,
        description: cat.description,
        sortOrder: cat.sortOrder,
      },
    });
    categoryMap.set(cat.slug, record.id);
  }
  console.log(`✓ Seeded ${categoryMap.size} categories.`);

  // 2. Upsert tools
  let count = 0;
  for (const tool of FREE_AND_FREEMIUM_TOOLS) {
    const categoryId = categoryMap.get(tool.categorySlug) ?? null;
    const logoUrl = getFaviconUrl(tool.websiteUrl);

    await prisma.aITool.upsert({
      where: { slug: tool.slug },
      update: {
        name: tool.name,
        tagline: tool.tagline,
        description: tool.description,
        websiteUrl: tool.websiteUrl,
        logoUrl,
        pricingType: tool.pricingType,
        priceStart: tool.priceStart,
        rating: tool.rating,
        reviewCount: tool.reviewCount,
        isFeatured: tool.isFeatured,
        isVerified: tool.isVerified,
        ...(categoryId ? { categoryId } : {}),
      },
      create: {
        slug: tool.slug,
        name: tool.name,
        tagline: tool.tagline,
        description: tool.description,
        websiteUrl: tool.websiteUrl,
        logoUrl,
        pricingType: tool.pricingType,
        priceStart: tool.priceStart,
        rating: tool.rating,
        reviewCount: tool.reviewCount,
        isFeatured: tool.isFeatured,
        isVerified: tool.isVerified,
        categoryId,
      },
    });
    count++;
  }

  console.log(`✓ Successfully seeded ${count} free & freemium AI tools into Supabase!`);
  return count;
}

if (require.main === module) {
  seedFreeTools()
    .catch((err) => {
      console.error("Error during seed:", err);
      process.exit(1);
    })
    .finally(() => prisma.$disconnect());
}

